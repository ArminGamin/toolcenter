function haystack(text: string): string {
  return ` ${text.toLowerCase()} `
}

function keyHits(text: string, key: string): number {
  const k = key.toLowerCase().trim()
  if (!k) return 0
  const h = haystack(text)
  if (k.includes(' ')) return h.includes(k) ? 1 : 0
  const re = new RegExp(`[^a-z]${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[a-z]*[^a-z]`, 'i')
  return re.test(h) ? 1 : 0
}

export function scoreLexemeAgainstText(text: string, entry: CaptionLexeme): number {
  let hits = 0
  let weight = 0
  for (const key of entry.keys) {
    if (!keyHits(text, key)) continue
    hits += 1
    weight += key.includes(' ') ? 3 : 1
  }
  if (!hits) return 0
  return weight + hits * 2
}

export function rankCaptionsForText(text: string): { term: string; score: number }[] {
  return ONE_SHOT_CAPTION_LEXICON.map((entry) => ({
    term: entry.term,
    score: scoreLexemeAgainstText(text, entry),
  }))
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score || a.term.localeCompare(b.term))
}
